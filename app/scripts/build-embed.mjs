// Builds the prototype into one offline page for the store app (David, 2026-11-09: the app wraps the
// prototype, so every change to prototype/ carries over).
//
//   node scripts/build-embed.mjs        (run from app/, after any change to prototype/)
//
// Writes src/embedded/page.ts, which exports the whole page as a string: the app shows it in a web view
// (iOS, Android) or an iframe (web). Into the one file go:
//   - app.js with ts-fsrs, bundled by esbuild into a plain script;
//   - style.css, with the fonts (Vollkorn, Inter, and Gentium Plus for accented Greek, which Vollkorn
//     lacks) inlined from @fontsource, in place of the Google Fonts link, so nothing needs the network;
//   - the data files and the logo, served to the page's fetch() calls from memory;
//   - the icons, as data: URLs.
// The page reads window.__TERTIUS (set by the app before it loads) for saving, outside links, and audio.
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const APP = join(dirname(fileURLToPath(import.meta.url)), "..");
const PROTO = join(APP, "..", "prototype");
const read = (p, enc = "utf8") => readFileSync(join(PROTO, p), enc);

// 1. app.js and ts-fsrs as one classic script.
const js = (await build({
  entryPoints: [join(PROTO, "app.js")], bundle: true, write: false, format: "iife",
  target: ["es2020", "safari15", "chrome100"], legalComments: "none", charset: "utf8",
})).outputFiles[0].text;

// 2. Fonts, inlined.
const FONTS = [
  ["vollkorn", ["latin", "latin-ext", "greek"], ["400", "600", "800", "400-italic"]],
  ["inter", ["latin", "latin-ext"], ["400", "500", "600"]],
  ["gentium-plus", ["latin", "greek", "greek-ext"], ["400", "700", "400-italic"]],
];
let fontCss = "";
for (const [family, subsets, weights] of FONTS) {
  const dir = join(APP, "node_modules", "@fontsource", family);
  for (const w of weights) {
    // Each weight's file has one @font-face per subset, with its unicode-range; keep the subsets we use.
    const blocks = readFileSync(join(dir, `${w}.css`), "utf8").split(/(?=\/\* )/);
    for (const b of blocks) {
      const sub = (b.match(/^\/\* [a-z-]+?-((?:latin|greek|cyrillic|vietnamese)(?:-ext)?)-\d+-(?:normal|italic) \*\//) || [])[1];
      if (!subsets.includes(sub)) continue;
      fontCss += b.replace(/url\(\.\/files\/([^)]+)\.woff2\) format\('woff2'\)(, url\([^)]+\) format\('woff'\))?/g,
        (_, f) => `url(data:font/woff2;base64,${readFileSync(join(dir, "files", f + ".woff2")).toString("base64")}) format('woff2')`);
    }
  }
}
// 3. Files the page fetches.
const files = {};
for (const f of readdirSync(join(PROTO, "data"))) if (f.endsWith(".json")) files[`data/${f}`] = read(`data/${f}`);
files["icons/mark.svg"] = read("icons/mark.svg");

// 4. The page.
const dataUrl = (p, type) => `data:${type};base64,${readFileSync(join(PROTO, p)).toString("base64")}`;
let html = read("index.html")
  .replace(/\s*<link rel="preconnect"[^>]*>/g, "")
  .replace(/\s*<link href="https:\/\/fonts\.googleapis\.com[^>]*>/, "")
  .replace(/\s*<link rel="manifest"[^>]*>/, "")
  .replace(/href="icons\/favicon\.svg"/, `href="${dataUrl("icons/favicon.svg", "image/svg+xml")}"`)
  .replace(/href="icons\/favicon-32\.png"/, `href="${dataUrl("icons/favicon-32.png", "image/png")}"`)
  .replace(/href="icons\/icon-180\.png"/, `href="${dataUrl("icons/icon-180.png", "image/png")}"`)
  .replace(/\s*<link rel="stylesheet" href="style\.css">/, () => `\n<style>${fontCss}\n${read("style.css")}</style>`);
// Served from memory: the page's fetch() of a bundled file never touches the network.
const boot = `window.__TERTIUS_FILES=${JSON.stringify(files)};
(function(){var F=window.__TERTIUS_FILES,f0=window.fetch&&window.fetch.bind(window);
window.fetch=function(u,o){var k=String(u&&u.url||u).replace(/^\\.\\//,"");
if(Object.prototype.hasOwnProperty.call(F,k))return Promise.resolve(new Response(F[k],{status:200,headers:{"Content-Type":/\\.json$/.test(k)?"application/json":"image/svg+xml"}}));
return f0?f0(u,o):Promise.reject(new Error("offline"));};})();`;
const script = (s) => `<script>${s.replace(/<\/(script)/gi, "<\\/$1")}</script>`;
html = html.replace(/\s*<script type="module" src="app\.js"><\/script>/, () => `\n${script(boot)}\n${script(js)}`);
if (/src="app\.js"|style\.css|fonts\.googleapis/.test(html)) throw new Error("page still links a prototype file");

mkdirSync(join(APP, "src", "embedded"), { recursive: true });
writeFileSync(join(APP, "src", "embedded", "page.ts"),
  `// Generated by scripts/build-embed.mjs from prototype/: do not edit. Rebuild after changing the prototype.\n` +
  `/* eslint-disable */\nconst page: string = ${JSON.stringify(html)};\nexport default page;\n`);
writeFileSync(join(APP, "src", "embedded", "page.html"), html); // for opening in a browser to check
console.log(`page ${(html.length / 1e6).toFixed(2)} MB (data ${(JSON.stringify(files).length / 1e6).toFixed(2)} MB, fonts ${(fontCss.length / 1e6).toFixed(2)} MB, script ${(js.length / 1e3).toFixed(0)} kB)`);
