def entries():
    src = (ROOT / "data/grammars/blass-noteworthy-verbs.md").read_text(encoding="utf-8").split("\n---\n", 1)[1]
    out, page = [], "52"
    for p in (p.strip() for p in src.split("\n\n")):
        if not p or p.startswith("## ") or p.startswith("(The prefixing"):
            continue
        m = re.match(r"^\*\[p\. (\d+)\]\*\s*", p)
        if m:
            page, p = m.group(1), p[m.end():].strip()
            if not p:
                continue
        h = re.match(r"^[\(\[]?\*\*\\?\*?([^*,.( \]]+)", p)
        if h and p[:3].lstrip("([").startswith("**"):
            out.append({"head": h.group(1), "text": p, "p": page})
        else:
            out[-1]["text"] += " " + p
            if page != out[-1]["p"].split("–")[0]:
                out[-1]["p"] = out[-1]["p"].split("–")[0] + "–" + page
    return out


def plain(t: str) -> str:
    t = re.sub(r"\*\[p\. (\d+)\]\*\s*", "", t).replace("\\*", "∗").replace("**", "")
    return re.sub(r"(?<![\w∗])\*([^*]+)\*", r"\1", t).replace("∗", "*")


def main() -> None:
    lemmas = {l.split("\t")[0] for l in (ROOT / "data/nt/lemmas.tsv").read_text(encoding="utf-8").splitlines()[1:]}
    E, by = [], {}
    for i, e in enumerate(entries()):
        key = e["head"]
        if key == "Λέγειν":
            key = "Λέγειν/collect" if "collect" in e["text"][:40] else "Λέγειν/say"
        for l in M[key].split():
            assert l in lemmas, (key, l)
            by.setdefault(l, []).append(i)
        E.append({"h": plain(re.match(r"^[\(\[]?\*\*(.+?)\*\*", e["text"]).group(1)), "t": plain(e["text"]), "p": e["p"]})

    out = ROOT / "prototype/data/blass24.json"
    out.write_text(json.dumps({"e": E, "l": by}, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"{len(E)} entries, {len(by)} lemmas -> {out}")


if __name__ == "__main__":
    main()
